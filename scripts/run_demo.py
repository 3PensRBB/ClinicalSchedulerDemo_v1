"""End-to-end demo pipeline.

    python3 scripts/run_demo.py build       # synthetic data -> PTO decisions -> 13-month schedule
    python3 scripts/run_demo.py scenarios   # runs PRD scenarios S2-S6, writes docs/demo_results.md
    python3 scripts/run_demo.py all
"""

from __future__ import annotations

import copy
import sys
import time
from collections import Counter
from datetime import date, timedelta
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from engine.pto import decide_requests  # noqa: E402
from engine.solver import generate_schedule  # noqa: E402
from engine.tools import (apply_callout, describe, find_replacement, request_pto, resign,  # noqa: E402
                          suggest_dates, swap)
from engine.validate import summary, violations  # noqa: E402
from engine.world import DATA_DIR, Schedule, World, daterange  # noqa: E402
from sim.generate_roster import generate  # noqa: E402

SCHEDULE = DATA_DIR / "schedule.json"


def build(seed: int = 42) -> tuple[World, Schedule, dict]:
    t0 = time.time()
    generate(seed=seed)
    world, sched = World.load(), Schedule()
    t1 = time.time()
    decide_requests(world, sched)
    t2 = time.time()
    generate_schedule(world, sched, progress=lambda a, b, r: print(f"  {a} → {b}  {r.status:8} {r.seconds:4.1f}s"))
    t3 = time.time()
    sched.log.append({"action": "generate", "horizon": [world.start.isoformat(), world.end.isoformat()]})
    sched.save(SCHEDULE)
    timing = {"data_s": round(t1 - t0, 1), "pto_s": round(t2 - t1, 1), "solve_s": round(t3 - t2, 1)}
    print("Timing:", timing)
    print("Summary:", summary(world, sched))
    return world, sched, timing


def _md_table(rows: list[dict], cols: list[str]) -> str:
    out = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    out += ["| " + " | ".join(str(r.get(c, "")) for c in cols) + " |" for r in rows]
    return "\n".join(out)


def scenarios(world: World | None = None, base: Schedule | None = None, timing: dict | None = None) -> str:
    world = world or World.load()
    base = base or Schedule.load(SCHEDULE)
    md = ["# Demo results (seed 42)", "",
          "Generated by `python3 scripts/run_demo.py all`. All people are fictional.", ""]

    # S1 ------------------------------------------------------------------
    s = summary(world, base)
    dec = Counter(d["status"] for d in base.decisions)
    md += ["## S1: Build the 13-month schedule", "",
           f"Horizon **{world.start} → {world.end}**, {len(world.techs)} techs, {len(world.holidays)} federal holidays.", ""]
    if timing:
        md += [f"- Time: PTO decisions **{timing['pto_s']} s**, full schedule solve **{timing['solve_s']} s**."]
    md += [f"- PTO requests decided by seniority: {dec['approved']} approved, {dec['partial']} partly approved, "
           f"{dec['denied']} denied.",
           f"- Shifts assigned: **{s['assignments']}**. Hard-rule violations: **{s['hard_violations']}**. "
           f"Coverage gaps: **{s['coverage_gaps']}**.",
           f"- Soft-preference satisfaction: **{s['preference_satisfaction_pct']}%**. FT hours met: "
           f"**{s['ft_hours_met_pct']}%**. PRN shifts used: {s['prn_shifts']}.", ""]

    # S2 ------------------------------------------------------------------
    lo, hi = date(2026, 12, 20), date(2027, 1, 3)
    rows = [d for d in base.decisions if d["start"] <= hi.isoformat() and d["end"] >= lo.isoformat()]
    rows.sort(key=lambda d: (d["bench"], d["seniority_rank"]))
    md += ["## S2: The Christmas / New Year 2026 crunch", "",
           "Each request is decided in seniority order. Bench PTO limits tighten to 1 person in the "
           "blackout window (±3 days of a major holiday), and the holiday group that works the "
           "holiday has to be able to cover it.", "",
           _md_table([{**r, "dates": f"{r['start']} → {r['end']}", "rank": f"#{r['seniority_rank']}"} for r in rows],
                     ["name", "bench", "rank", "dates", "status", "reason"]), ""]
    xmas = date(2026, 12, 25)
    wk = Counter(world.by_id[t]["holiday_group"] for (t, d) in base.assign if d == xmas)
    md += [f"Christmas Day 2026 is worked by holiday group **{world.holidays[xmas]['working_group']}**: "
           f"{wk.get('1', 0)} group-1 shifts and {wk.get('2', 0)} group-2 shifts.", ""]

    # S3 ------------------------------------------------------------------
    sch = base.copy()
    ny = date(2027, 1, 1)
    sick = next(t for (t, d), (sh, b) in sorted(sch.assign.items()) if d == ny and sh == "N" and b == "Blood Bank")
    t0 = time.time()
    cands = find_replacement(world, sch, sick, ny)
    dt = time.time() - t0
    md += ["## S3: Call-out on New Year's night", "",
           f"**{describe(world, sch, sick, ny)}** calls in sick. Ranked replacements found in "
           f"**{dt * 1000:.0f} ms**:", "",
           _md_table([{**c, "why": "; ".join(c["why"])} for c in cands[:6]],
                     ["name", "home", "employment", "score", "why"]), ""]
    if cands:
        apply_callout(world, sch, sick, ny, cands[0]["tech"])
        v = violations(world, sch, ny - timedelta(days=7), ny + timedelta(days=7))
        md += [f"Applied **{cands[0]['name']}**. Hard-rule violations in that fortnight after the fix: **{len(v)}**.", ""]

    # S4 ------------------------------------------------------------------
    sch = base.copy()
    chem_day = [t for t in world.techs if t["home_dept"] == "Chemistry" and t["employment"] == "FT"]
    tech = max(chem_day, key=lambda t: t["seniority_rank"])
    d0, d1 = date(2027, 8, 2), date(2027, 8, 6)
    res = request_pto(world, sch, tech["id"], d0, d1)
    md += ["## S4: A late summer vacation on the published schedule", "",
           f"{tech['name']} (Chemistry, seniority #{tech['seniority_rank']}) asks for **{d0} → {d1}** after "
           f"the schedule is published. Status: **{res['status']}**. Bench-limit conflict days: "
           f"{', '.join(res['bench_limit_days']) or 'none'}. Coverage OK: {res['coverage_ok']}.", ""]
    if res["status"] == "blocked":
        t0 = time.time()
        alts = suggest_dates(world, sch, tech["id"], d0, d1)
        md += [f"The tool suggests the nearest open windows in **{time.time() - t0:.1f} s**: "
               + ", ".join(f"{a['start']} → {a['end']}" for a in alts) + ".", ""]
        if alts:
            d0, d1 = date.fromisoformat(alts[0]["start"]), date.fromisoformat(alts[0]["end"])
            res = request_pto(world, sch, tech["id"], d0, d1)
            md += [f"The tech takes **{d0} → {d1}**. Status: **{res['status']}**."]
    if res["status"] == "approved":
        md += [f"{len(res['removed'])} of the tech's shifts became PTO. Repair re-solved the affected weeks in "
               f"**{res['solve_seconds']} s** ({res['solve_status']}) and made **{res['backfilled']}** other changes "
               "(slots that were above minimum don't need a backfill). Everything else stayed as published:", "",
               _md_table([{**c, "name": world.by_id[c["tech"]]["name"]} for c in res["changes"][:15]],
                         ["date", "name", "before", "after"])]
    md += [""]

    # S6 ------------------------------------------------------------------
    sch = base.copy()
    md += ["## S6: Swap requests", ""]
    found = None
    for (a, da), (sa, ba) in sorted(sch.assign.items()):
        if da < date(2027, 2, 1) or da.weekday() != 5:
            continue
        for b in world.techs:
            if b["id"] == a or not world.qualified(b, ba) or (b["id"], da) in sch.assign or sch.on_pto(b["id"], da):
                continue
            for db in daterange(da - timedelta(days=5), da - timedelta(days=1)):
                sb = sch.assign.get((b["id"], db))
                if sb and (a, db) not in sch.assign and not sch.on_pto(a, db) and world.qualified(world.by_id[a], sb[1]):
                    trial = sch.copy()
                    if not swap(world, trial, a, da, b["id"], db):
                        found = (a, da, b["id"], db)
                        break
            if found:
                break
        if found:
            break
    if found:
        a, da, b, db = found
        before = [describe(world, sch, a, da), describe(world, sch, b, db)]
        v = swap(world, sch, a, da, b, db)
        md += [f"- **Valid swap:** {before[0]} ↔ {before[1]} → violations: **{len(v)}** (approved).", ""]
    sch = base.copy()
    a, da = next(((t, d) for (t, d), (sh, b) in sorted(sch.assign.items())
                  if b == "Blood Bank" and d >= date(2027, 2, 1)), (None, None))
    micro = next(t for t in world.techs if t["home_dept"] == "Microbiology" and not world.qualified(t, "Blood Bank")
                 and (t["id"], da) not in sch.assign)
    v = swap(world, sch, a, da, micro["id"], da)
    md += [f"- **Invalid swap:** {world.by_id[a]['name']} gives a Blood Bank shift on {da} to {micro['name']} → "
           f"blocked, violations: " + "; ".join(x["detail"] for x in v[:3]), ""]

    # S5 (mutates world: run last) -----------------------------------------
    sch, w2 = base.copy(), copy.deepcopy(world)
    w2.__post_init__()
    leaver = next(t for t in w2.techs if t["home_dept"] == "Chemistry" and t["shift_pref"] == "Days"
                  and t["employment"] == "FT")
    eff = date(2027, 3, 1)
    res = resign(w2, sch, leaver["id"], eff)
    post = summary(w2, sch)
    md += ["## S5: Resignation", "",
           f"{leaver['name']} (Chemistry Days, FT) resigns effective **{eff}**. Re-solving the remaining "
           f"{(w2.end - eff).days // 7} weeks took **{res['solve_seconds']} s**. {res['shifts_removed']} shifts were removed, "
           f"and **{res['changes_to_others']}** assignments changed for other staff.",
           f"After the repair: coverage gaps **{post['coverage_gaps']}**, hard violations **{post['hard_violations']}**, "
           f"PRN shifts {post['prn_shifts']} (was {s['prn_shifts']}), preference satisfaction "
           f"{post['preference_satisfaction_pct']}%.", ""]

    text = "\n".join(md)
    (ROOT / "docs" / "demo_results.md").write_text(text)
    print(text)
    return text


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else "all"
    if cmd == "build":
        build()
    elif cmd == "scenarios":
        scenarios()
    else:
        w, s, tm = build()
        scenarios(w, s, tm)
